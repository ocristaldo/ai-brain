#!/usr/bin/env python3
"""Run pytest with coverage and write a test report to project logs."""
import json
import re
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOG_REPORTS_DIR = ROOT / "logs" / "test_reports"
REPORT_CMD = [
    "pytest",
    "-v",
    "--cov=.",
    "--cov-report=term",
    "--cov-report=json:cov.json",
]

TRIMMED_LINE_RE = re.compile(r"=+\s*(.+?)\s*=+")
STATUS_TOKENS = ("PASSED", "FAILED", "SKIPPED", "XFAIL", "XPASS")

# Regex to extract all components from a test line
LINE_RE = re.compile(
    r"""^tests/(.*?)::        # 1) file path under tests/
        (.*?)\s+              # 2) test name
        (PASSED|FAILED|SKIPPED|XFAIL|XPASS)\s+  # 3) status
        \[\s*(\d{1,3})%\]     # 4) first percent (progress)
        (?:.*?\[\s*(\d{1,3})%\])?  # 5) second percent (coverage, optional)
    """,
    re.VERBOSE,
)

def parse_test_line(line: str):
    """Parse a pytest output line into its components."""
    m = LINE_RE.search(line)
    if not m:
        return None
    file_path, test_name, status, pct1, pct2 = m.groups()
    file_name = file_path.split("/")[-1]  # "tests/foo/bar.py" -> "bar.py"
    first_percent = f"{pct1}%"
    second_percent = f"{pct2}%" if pct2 is not None else None
    return [file_name, test_name, status, first_percent, second_percent]

def run_pytest():
    start = time.perf_counter()
    proc = subprocess.run(
        REPORT_CMD,
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    duration = time.perf_counter() - start
    # Mirror output so devs still see the pytest stream
    sys.stdout.write(proc.stdout)
    sys.stderr.write(proc.stderr)
    proc.check_returncode()
    return duration, proc.stdout + proc.stderr

def parse_summary(output: str):
    summary_line = ""
    for line in output.splitlines()[::-1]:
        lower = line.lower()
        if "passed" in lower or "failed" in lower:
            summary_line = line.strip()
            break
    if not summary_line:
        return ""
    match = TRIMMED_LINE_RE.match(summary_line)
    summary_text = match.group(1) if match else summary_line
    emoji = "✅" if "passed" in summary_text.lower() else "❌"
    return f"{emoji} {summary_text}"


def extract_test_lines(output: str):
    """Extract test lines with coverage info from pytest output."""
    test_results = []
    
    for line in output.splitlines():
        if "::" in line and any(status in line for status in STATUS_TOKENS):
            test_line = line.strip()
            parsed = parse_test_line(test_line)
            if parsed:
                test_results.append(parsed)
            
    return test_results


def coverage_badge(percent):
    if percent is None:
        return "N/A"
    try:
        pct = float(percent)
        return f"{pct:.1f}%"
    except (TypeError, ValueError):
        return percent


def build_detail_table(rows):
    if not rows:
        return "See pytest log above."
    
    table = ["| File | Test | Status | Coverage |", "| --- | --- | --- | --- |"]
    
    for file_name, test_name, status, coverage, total in rows:
        # Map status to icons
        status_icon = {
            "PASSED": "✅",
            "FAILED": "❌",
            "SKIPPED": "⚠️",
            "XFAIL": "⚠️",
            "XPASS": "⚠️"
        }.get(status, "⚠️")
        
        status_text = f"{status_icon} {status}"
        coverage_text = coverage if coverage is not None else ""
                
        table.append(f"| `{file_name}` | `{test_name}` | {status_text} | {coverage_text} |")
        
    return "\n".join(table)

def load_coverage():
    cov_path = ROOT / "cov.json"
    if not cov_path.exists():
        return None
    with cov_path.open() as fh:
        data = json.load(fh)
    return data.get("totals", {})

def write_report(duration: float, summary_line: str, coverage: dict, details):
    timestamp = datetime.now().astimezone()
    iso = timestamp.isoformat().replace(":", "-")
    destinations = []

    cov_percent = coverage.get("percent_covered_display") or coverage.get("percent_covered")
    lines = coverage.get("covered_lines")
    total = coverage.get("num_statements")

    detail_table = build_detail_table(details)
    human_time = timestamp.strftime("%Y-%m-%d %H:%M:%S %Z")

    report_body = f"""# Test Report — {timestamp.date()}

_Run at {human_time}_

## Command
`{' '.join(REPORT_CMD)}`

## Result
- Summary: {summary_line or 'See pytest output above'}
- Duration: {duration:.2f}s

## Detailed Results
{detail_table}

## Coverage
- Covered lines: {lines if lines is not None else 'N/A'} / {total if total is not None else 'N/A'}
- Percent covered: {coverage_badge(cov_percent)}

*Report auto-generated by `scripts/run_tests.py`.*
"""

    LOG_REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    destinations.append(LOG_REPORTS_DIR / f"{iso}-test-report.md")
    destinations.append(LOG_REPORTS_DIR / "latest-test-report.md")

    for path in destinations:
        path.write_text(report_body, encoding="utf-8")

    trim_old_reports()


def trim_old_reports(keep: int = 5):
    """Keep only the most recent `keep` timestamped reports plus latest."""
    if not LOG_REPORTS_DIR.exists():
        return
    latest = LOG_REPORTS_DIR / "latest-test-report.md"
    files = [p for p in LOG_REPORTS_DIR.glob("*-test-report.md") if p.name != latest.name]
    files.sort(key=lambda p: p.stat().st_mtime, reverse=True)
    for old in files[keep:]:
        try:
            old.unlink()
        except OSError:
            pass


def main():
    duration, output = run_pytest()
    coverage = load_coverage() or {}
    summary_line = parse_summary(output)
    details = extract_test_lines(output)
    write_report(duration, summary_line, coverage, details)


if __name__ == "__main__":
    main()
